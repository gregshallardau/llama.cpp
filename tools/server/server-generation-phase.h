// Experimental, header-only generation phase tracker.
// Phase observation never mutates tokens, sampling, or KV cache.
// Markers come from model/template-specific configuration; no model
// vocabulary or Jinja syntax is assumed here.
#pragma once

#include <algorithm>
#include <cstddef>
#include <string>
#include <utility>
#include <vector>

enum class server_generation_phase {
    response,
    reasoning,
    tool_call,
};

inline const char * server_generation_phase_name(server_generation_phase phase) {
    switch (phase) {
        case server_generation_phase::response:  return "response";
        case server_generation_phase::reasoning: return "reasoning";
        case server_generation_phase::tool_call: return "tool_call";
    }
    return "unknown";
}

struct server_generation_marker {
    std::string text;
    server_generation_phase phase;
    bool is_end;
};

// A transition offset is measured in generated BYTES, not KV token positions.
// The caller must separately map boundaries to token positions if required.
struct server_generation_transition {
    server_generation_phase phase;
    size_t byte_offset;
};

class server_generation_phase_tracker {
public:
    explicit server_generation_phase_tracker(std::vector<server_generation_marker> markers)
        : markers_(std::move(markers)) {
        std::stable_sort(markers_.begin(), markers_.end(),
            [](const auto & a, const auto & b) { return a.text.size() > b.text.size(); });
        for (const auto & marker : markers_) {
            max_marker_length_ = std::max(max_marker_length_, marker.text.size());
        }
    }

    server_generation_phase phase() const { return phase_; }

    std::vector<server_generation_transition> append(const std::string & chunk) {
        std::vector<server_generation_transition> events;
        if (chunk.empty()) {
            return events;
        }
        const size_t previous_bytes = seen_bytes_;
        seen_bytes_ += chunk.size();
        pending_ += chunk;
        // Keep enough bytes for a delimiter split across streaming chunks.
        // Matched complete markers are processed immediately.
        size_t cursor = 0;
        while (cursor < pending_.size()) {
            const server_generation_marker * match = nullptr;
            for (const auto & marker : markers_) {
                if (marker.text.empty() || cursor + marker.text.size() > pending_.size()) {
                    continue;
                }
                if (pending_.compare(cursor, marker.text.size(), marker.text) == 0) {
                    match = &marker;
                    break;
                }
            }
            if (match) {
                if (match->is_end) {
                    if (phase_ == match->phase) {
                        phase_ = server_generation_phase::response;
                        events.push_back({phase_, pending_base_ + cursor + match->text.size()});
                    }
                } else if (phase_ != match->phase) {
                    phase_ = match->phase;
                    events.push_back({phase_, pending_base_ + cursor});
                }
                cursor += match->text.size();
                continue;
            }

            // Don't consume a possible partial delimiter.
            bool prefix = false;
            for (const auto & marker : markers_) {
                if (!marker.text.empty() &&
                    pending_.size() - cursor < marker.text.size() &&
                    marker.text.compare(0, pending_.size() - cursor, pending_, cursor,
                                        pending_.size() - cursor) == 0) {
                    prefix = true;
                    break;
                }
            }
            if (prefix) {
                break;
            }
            ++cursor;
        }
        pending_.erase(0, cursor);
        pending_base_ += cursor;
        (void) previous_bytes;
        return events;
    }

private:
    std::vector<server_generation_marker> markers_;
    server_generation_phase phase_ = server_generation_phase::response;
    std::string pending_;
    size_t pending_base_ = 0;
    size_t seen_bytes_ = 0;
    size_t max_marker_length_ = 0;
};
